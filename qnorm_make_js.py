"""Generate v3_qnorm.js from qnorm_dict.json + qnorm_names.json (no external libraries; plain script, global `QN`)."""
import json
d = json.load(open('qnorm_dict.json', encoding='utf-8'))
names = json.load(open('qnorm_names.json', encoding='utf-8'))
vocab = json.load(open('qnorm_vocab.json', encoding='utf-8'))
JS = r'''/* v3_qnorm.js — generated by qnorm_make_js.py (E31). Colloquial question -> official wording, plus frame decomposition.
   Usage: QN.normalize(q)  | QN.frame(QN.normalize(q)) | QN.simQ(qNorm, officialQ) | QN.frameBonus(fq, fd, cardName)
   Wiring notes: docs/qnorm_integration.md */
const QN=(function(){
const D=__DICT__;
const NAMES=__NAMES__;
const VOCAB0=new Set(__VOCAB__);
const PRE=D.pre.map(x=>[new RegExp(x.p,'g'),x.r]);
const RULES=D.rules.map(x=>[new RegExp(x.p,'g'),x.r]);
const SLOTS=D.slots.map(x=>[x[0],x[1],new RegExp(x[2])]);
const ASK=D.ask.map(x=>[x[0],new RegExp(x[1])]);
const W=D.weights;
const STRIP=new Map();for(const n of NAMES)STRIP.set(n.replace(/ /g,''),n);
const BYLEN=[...STRIP.keys()].sort((a,b)=>b.length-a.length);
const PREFIX=new Map();
for(const n of STRIP.keys())for(let k=1;k<=4;k++)if(n.length-k>=3){const p=n.slice(0,n.length-k);if(!PREFIX.has(p))PREFIX.set(p,new Set());PREFIX.get(p).add(n)}
function clean(s){s=(s||'').normalize('NFC');for(const [p,r] of PRE)s=s.replace(p,r);return s}
function expandNames(s,vocab){return s.replace(/[가-힣]{3,}/g,t=>{if(STRIP.has(t)||VOCAB0.has(t)||(vocab&&vocab.has(t)))return t;const c=PREFIX.get(t);if(c&&c.size===1)return STRIP.get([...c][0]);return t})}
function normalize(q,names,vocab){let s=clean(q);for(const [p,r] of RULES)s=s.replace(p,r);if(names!==false)s=expandNames(s,vocab);return s.replace(/\s+/g,' ').trim()}
function cardsIn(s){const t=s.replace(/ /g,'');const found=[];const used=new Array(t.length).fill(false);
  for(const n of BYLEN){if(n.length<3)continue;const i=t.indexOf(n);if(i>=0){let free=true;for(let k=i;k<i+n.length;k++)if(used[k]){free=false;break}
    if(free){found.push(STRIP.get(n));for(let k=i;k<i+n.length;k++)used[k]=true}}}return found}
function frame(s){const timing=[...new Set(s.match(/【[^】]+】|《[^》]+》/g)||[])].sort();
  const slots=[...new Set(SLOTS.filter(x=>x[2].test(s)).map(x=>x[0]+':'+x[1]))].sort();
  let ask='';for(const [a,p] of ASK)if(p.test(s)){ask=a;break}return {cards:cardsIn(s),timing,slots,ask}}
function jset(a,b){a=new Set(a);b=new Set(b);if(!a.size||!b.size)return 0;let x=0;for(const v of a)if(b.has(v))x++;return x/(a.size+b.size-x)}
function frameBonus(fq,fd,cardName){let s=W.timing*jset(fq.timing,fd.timing)+W.slot*jset(fq.slots,fd.slots);
  if(fq.ask&&fq.ask===fd.ask)s+=W.ask;
  if(fq.cards.length&&(fq.cards.includes(cardName)||fq.cards.some(c=>fd.cards.includes(c))))s+=W.card;return s}
const END=/(?:할 수 (?:있|없)|수 (?:있|없)|되|하|한|인|입|있|없)?(?:나요|습니까|ㅂ니까|니까|가요|까요|나여)\s*[?]?\s*$/;
const STOP=/이 카드의|이 카드가|이 카드를|이 카드|이때,?|상황입니다\.?|경우/g;
function content(s){return s.replace(STOP,' ').trim().replace(END,'')}
function bigrams(s){const t=s.replace(/\s+/g,'');const o=new Set();for(let i=0;i<t.length-1;i++)o.add(t.slice(i,i+2));return o}
function simQ(a,b){const A=bigrams(a),B=bigrams(b);let x=0;for(const g of A)if(B.has(g))x++;return x/((A.size+B.size-x)||1)}
return {normalize,content,frame,frameBonus,cardsIn,bigrams,simQ,weights:W,rules:RULES.length};
})();
if(typeof module!=='undefined')module.exports=QN;
'''
open('v3_qnorm.js', 'w', encoding='utf-8').write(JS.replace('__DICT__', json.dumps(d, ensure_ascii=False)).replace('__NAMES__', json.dumps(names, ensure_ascii=False)).replace('__VOCAB__', json.dumps(vocab, ensure_ascii=False)))
